#ifndef CHASSIS_SPIN_CONFIG_H
#define CHASSIS_SPIN_CONFIG_H

/* 0: 沿用原有固定自旋目标; 1: 转速已跟上且功率有余量时提高自旋目标。 */
#ifndef CHASSIS_SPIN_ADAPTIVE_ENABLE
#define CHASSIS_SPIN_ADAPTIVE_ENABLE 1
#endif
#if CHASSIS_SPIN_ADAPTIVE_ENABLE != 0 && CHASSIS_SPIN_ADAPTIVE_ENABLE != 1
#error CHASSIS_SPIN_ADAPTIVE_ENABLE must be 0 or 1.
#endif

#define CHASSIS_SPIN_MODE_FIXED 0
#define CHASSIS_SPIN_MODE_ADAPTIVE 1
#define CHASSIS_SPIN_MODE_SINE 2
#ifndef CHASSIS_SPIN_MODE
#if CHASSIS_SPIN_ADAPTIVE_ENABLE
#define CHASSIS_SPIN_MODE CHASSIS_SPIN_MODE_SINE
#else
#define CHASSIS_SPIN_MODE CHASSIS_SPIN_MODE_FIXED
#endif
#endif
#if CHASSIS_SPIN_MODE < CHASSIS_SPIN_MODE_FIXED || CHASSIS_SPIN_MODE > CHASSIS_SPIN_MODE_SINE
#error CHASSIS_SPIN_MODE must be 0 (fixed), 1 (adaptive), or 2 (sine).
#endif
#define CHASSIS_SPIN_DYNAMIC_ENABLED (CHASSIS_SPIN_MODE != CHASSIS_SPIN_MODE_FIXED)

/* These use the existing chassis wz command units, not motor rpm. */
#ifndef CHASSIS_SPIN_FIXED_WZ
#define CHASSIS_SPIN_FIXED_WZ 4000.0f
#endif
#ifndef CHASSIS_SPIN_MIN_WZ
#define CHASSIS_SPIN_MIN_WZ 1000.0f
#endif
#ifndef CHASSIS_SPIN_MAX_WZ
#define CHASSIS_SPIN_MAX_WZ 6000.0f
#endif
#ifndef CHASSIS_SPIN_POWER_GAIN
#define CHASSIS_SPIN_POWER_GAIN 40.0f
#endif
#ifndef CHASSIS_SPIN_RISE_RATE
#define CHASSIS_SPIN_RISE_RATE 400.0f
#endif
#ifndef CHASSIS_SPIN_FALL_RATE
#define CHASSIS_SPIN_FALL_RATE 2000.0f
#endif
#ifndef CHASSIS_SPIN_POWER_LPF_TAU_S
#define CHASSIS_SPIN_POWER_LPF_TAU_S 0.1f
#endif
#ifndef CHASSIS_SPIN_POWER_DEADBAND_W
#define CHASSIS_SPIN_POWER_DEADBAND_W 1.0f
#endif
#ifndef CHASSIS_SPIN_SETTLE_TIME_S
#define CHASSIS_SPIN_SETTLE_TIME_S 0.2f
#endif
#ifndef CHASSIS_SPIN_TRACKING_ERROR_RPM
#define CHASSIS_SPIN_TRACKING_ERROR_RPM 500.0f
#endif
#ifndef CHASSIS_SPIN_BUDGET_DROP_RESET_W
#define CHASSIS_SPIN_BUDGET_DROP_RESET_W 1.0f
#endif

/* 正弦使用独立的可跟随目标；默认麦轮几何下稳态约为 3403..5672 rpm。
 * 沿用 4000 的中心会要求约 22689 rpm，使跟随/功率保护阻止振幅建立。 */
#ifndef CHASSIS_SPIN_SINE_CENTER_WZ
#define CHASSIS_SPIN_SINE_CENTER_WZ 800.0f
#endif
#ifndef CHASSIS_SPIN_SINE_MIN_WZ
#define CHASSIS_SPIN_SINE_MIN_WZ 200.0f
#endif
#ifndef CHASSIS_SPIN_SINE_AMPLITUDE_WZ
#define CHASSIS_SPIN_SINE_AMPLITUDE_WZ 200.0f
#endif
#ifndef CHASSIS_SPIN_SINE_PERIOD_S
#define CHASSIS_SPIN_SINE_PERIOD_S 4.0f
#endif
#ifndef CHASSIS_SPIN_SINE_RAMP_S
#define CHASSIS_SPIN_SINE_RAMP_S 1.0f
#endif
#ifndef CHASSIS_SPIN_SINE_RISE_RATE
#define CHASSIS_SPIN_SINE_RISE_RATE 400.0f
#endif
#ifndef CHASSIS_SPIN_SINE_FALL_RATE
#define CHASSIS_SPIN_SINE_FALL_RATE 2000.0f
#endif
#ifndef CHASSIS_SPIN_SINE_DIRECTION
#define CHASSIS_SPIN_SINE_DIRECTION 1
#endif

#endif
